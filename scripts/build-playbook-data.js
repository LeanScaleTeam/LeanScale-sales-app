#!/usr/bin/env node
/**
 * Build-time script: playbooks-content/ → data/playbook-content.js + data/playbook-registry.json
 *
 * Replaces scripts/fetch-playbooks.js. Reads from the local playbooks-content/
 * directory (submodule or embedded) and generates the JS module consumed by
 * the Sales App at runtime.
 *
 * Run as prebuild: node scripts/build-playbook-data.js
 */

const fs = require('fs');
const path = require('path');

const CONTENT_DIR = path.join(__dirname, '..', 'playbooks-content');
const REGISTRY_PATH = path.join(CONTENT_DIR, 'registry.json');
const ALIASES_PATH = path.join(CONTENT_DIR, 'id-aliases.json');
const PLAYBOOKS_DIR = path.join(CONTENT_DIR, 'playbooks');

const OUTPUT_CONTENT = path.join(__dirname, '..', 'data', 'playbook-content.js');
const OUTPUT_REGISTRY = path.join(__dirname, '..', 'data', 'playbook-registry.json');

function loadJSON(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function readMarkdown(slug, page) {
  const filePath = path.join(PLAYBOOKS_DIR, slug, `${page}.md`);
  if (!fs.existsSync(filePath)) return null;
  return fs.readFileSync(filePath, 'utf8');
}

function readMeta(slug) {
  const filePath = path.join(PLAYBOOKS_DIR, slug, 'meta.json');
  if (!fs.existsSync(filePath)) return null;
  return loadJSON(filePath);
}

function buildContent() {
  if (!fs.existsSync(REGISTRY_PATH)) {
    if (fs.existsSync(OUTPUT_CONTENT)) {
      console.log('playbooks-content/ submodule not initialized — using committed data/playbook-content.js');
      return;
    }
    console.error('registry.json not found and no committed playbook-content.js exists.');
    console.error('Run: git submodule update --init');
    process.exit(1);
  }

  const registry = loadJSON(REGISTRY_PATH);
  const aliases = loadJSON(ALIASES_PATH);
  const content = {};

  for (const playbook of registry.playbooks) {
    const slug = playbook.slug;
    const meta = readMeta(slug);

    const advisory = readMarkdown(slug, 'advisory');
    const methodology = readMarkdown(slug, 'methodology');
    const implementation = readMarkdown(slug, 'implementation');

    if (playbook.status === 'stub' || (!advisory && !methodology && !implementation)) {
      content[slug] = { status: 'stub', meta };
      continue;
    }

    content[slug] = {
      status: 'published',
      meta,
      advisory: advisory || '',
      methodology: methodology || '',
      implementation: implementation || '',
    };
  }

  // Create alias entries pointing to canonical content
  for (const [oldId, newSlug] of Object.entries(aliases.aliases)) {
    if (content[newSlug]) {
      content[oldId] = { ...content[newSlug], aliasOf: newSlug };
    }
  }

  // Generate JS module (ES module export)
  const jsContent = `// AUTO-GENERATED by scripts/build-playbook-data.js
// Do not edit manually. Source: playbooks-content/ submodule.
// Generated: ${new Date().toISOString()}
export const playbookContent = ${JSON.stringify(content, null, 2)};
`;

  fs.writeFileSync(OUTPUT_CONTENT, jsContent);
  fs.writeFileSync(OUTPUT_REGISTRY, JSON.stringify(registry, null, 2));

  const publishedCount = Object.values(content).filter(c => c.status === 'published' && !c.aliasOf).length;
  const stubCount = Object.values(content).filter(c => c.status === 'stub' && !c.aliasOf).length;
  const aliasCount = Object.values(content).filter(c => c.aliasOf).length;

  console.log(`Built playbook data:`);
  console.log(`  Published: ${publishedCount}`);
  console.log(`  Stubs: ${stubCount}`);
  console.log(`  Aliases: ${aliasCount}`);
  console.log(`  Total entries: ${Object.keys(content).length}`);
  console.log(`\nOutput:`);
  console.log(`  ${OUTPUT_CONTENT}`);
  console.log(`  ${OUTPUT_REGISTRY}`);
}

buildContent();
